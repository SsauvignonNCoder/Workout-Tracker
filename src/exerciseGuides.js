// Нормализация для запасного сравнения (ё→е, нижний регистр).
function norm(s) {
  return (s || '').toLowerCase().replace(/ё/g, 'е').trim();
}

// Возвращает подсказку для упражнения или null, если подходящей карточки нет.
export function getExerciseGuide(name) {
  const n = norm(name);
  if (!n) return null;
  for (const g of EXERCISE_GUIDES) {
    if (g.exclude && g.exclude.test(n)) continue;
    if (g.match.test(n)) return g;
  }
  return null;
}
