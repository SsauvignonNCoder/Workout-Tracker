// Наборы по «профилю» дня. Ключи выбираются по названию дня программы.
export const COOLDOWN_SETS = {
  upper: [SPINE_HANG, CHEST_DOOR, CAT_COW],
  legs: [CHILD_POSE, HIP_FLEXOR, HAMSTRING],
  arms: [SPINE_HANG, FOREARM, TRICEPS],
  cardio: [CALF, HIP_FLEXOR, BREATHING],
  general: [SPINE_HANG, CHILD_POSE, HIP_FLEXOR],
};

// Возвращает набор заминки для дня программы. Для бассейна — null (заминка не нужна:
// вода сама разгружает позвоночник, растяжка делается в воде).
export function cooldownFor(day) {
  if (!day) return null;
  if (day.type === 'pool') return null;
  if (day.type === 'cardio') return COOLDOWN_SETS.cardio;
  const title = String(day.title || '');
  if (title.includes('Ноги')) return COOLDOWN_SETS.legs;
  if (title.includes('Руки')) return COOLDOWN_SETS.arms;
  if (title.includes('Грудь') || title.includes('спина') || title.includes('плечи')) return COOLDOWN_SETS.upper;
  return COOLDOWN_SETS.general;
}
