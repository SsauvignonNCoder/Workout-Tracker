-- Миграция 1.0.5: пересчёт programDay после перехода 20 → 24 дня.
--
-- 13 августа цикл вырос с 20 дней (4 недели по 5) до 24 (4 недели по 6).
-- Позиция дня внутри недели считается как (day-1) % длина_недели, поэтому все
-- номера, записанные ДО перехода, стали указывать на чужой шаблон: день 11 был
-- «Грудь, спина, плечи», а стал «Руки, кор». Из-за этого недельный отчёт
-- помечал пропущенными упражнения, которых в тот день и не планировалось.
--
-- Пересчёт сохраняет неделю и позицию:
--   неделя = (старый-1)/5 + 1,  позиция = (старый-1)%5 + 1
--   новый  = (неделя-1)*6 + позиция
-- Проверено на всех 27 записях: шаблон дня совпал с тем, что реально сделано.
--
-- Границу подставить свою — момент выкладки версии с шестидневной неделей.
-- Записи после неё не трогать: они уже в новой нумерации.
--
-- Откат: старый = ((новый-1)/6)*5 + ((новый-1)%6) + 1
-- (однозначен, потому что позиция 6 — суббота — в старых данных не встречается).

create table if not exists public.program_day_backup_20260815 as
select id, user_id, date, program_day, created_at
from public.sessions
where program_day is not null
  and created_at < '2026-08-13 13:00:00+00';

update public.sessions
set program_day = ((program_day - 1) / 5) * 6 + ((program_day - 1) % 5) + 1
where program_day is not null
  and created_at < '2026-08-13 13:00:00+00';
