-- Миграция 1.0.3: название выбранного маршрута для кардио-дня по секторам.
--
-- Если на шаге «Высота» взят готовый маршрут («Озеро Зеркальное»), его название
-- сохраняется вместе с тренировкой, чтобы в «Прогрессе» она называлась горой,
-- а не безликим «Кардио по секторам».
--
-- Колонка опциональна: у тренировок без выбранного маршрута остаётся NULL.
-- Идемпотентна — можно выполнять повторно.
alter table public.sessions
  add column if not exists route_name text;
