-- ============================================================
-- 1.1.0 — несколько планов тренировок.
--
-- sessions.plan_id — к какому плану относится program_day тренировки.
-- Номер дня — ссылка на шаблон ВНУТРИ плана: «день 7» в старом и новом
-- плане — разные тренировки, и без plan_id экспорт недели сверял бы запись
-- не с тем шаблоном.
--
-- profile.plan_id — какой план сейчас ведётся (выбирается в «Профиле»).
--
-- Значение по умолчанию 'plan1' — старый план: все тренировки и профили,
-- созданные до 1.1.0, относятся к нему. Колонки добавляются с константным
-- default — в Postgres 11+ это мгновенно, без перезаписи таблицы.
--
-- Порядок выкладки: СНАЧАЛА эта миграция, потом фронтенд 1.1.0. Старый
-- фронтенд колонку не знает и не трогает: при вставке берётся default,
-- при upsert существующей строки она не меняется.
--
-- Идемпотентна — можно выполнять повторно.
-- ============================================================
alter table public.sessions add column if not exists plan_id text not null default 'plan1';
alter table public.profile add column if not exists plan_id text not null default 'plan1';
