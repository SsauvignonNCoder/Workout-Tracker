-- ============================================================
-- Версия 1.0.0 — время записи веса
-- Выполнить в Supabase: SQL Editor → New query → Run
--
-- Колонка называется time_of_day, а не time: слово time в SQL занято
-- под тип данных, и с ним PostgREST ведёт себя непредсказуемо.
-- Внутри приложения поле называется просто time, формат 'ЧЧ:ММ'.
--
-- Колонка nullable: у всех замеров, сделанных до 1.0.0, времени нет —
-- в интерфейсе рядом с датой у них просто ничего не показывается.
-- Повторный запуск безопасен (if not exists).
-- ============================================================

alter table public.measurements add column if not exists time_of_day text;
